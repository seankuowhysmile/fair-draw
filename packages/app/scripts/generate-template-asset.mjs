// Pre-build step: base64-embeds the example Excel template into a TS module,
// the same way v1's build.py inlined it into the single HTML file with
// base64.b64encode(...). Run before `vite dev`/`vite build` (see package.json).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const templatePath = resolve(here, '../../examples/sample/抽獎設定範本.xlsx');
const outDir = resolve(here, '../src/generated');
const outFile = resolve(outDir, 'template.ts');

const bytes = readFileSync(templatePath);
const base64 = bytes.toString('base64');

mkdirSync(outDir, { recursive: true });
writeFileSync(
  outFile,
  `// Auto-generated by scripts/generate-template-asset.mjs — do not edit by hand.\nexport const TEMPLATE_BASE64 = ${JSON.stringify(base64)};\n`,
);

console.log('Embedded template asset:', templatePath, '->', outFile, `(${bytes.length} bytes)`);
